const kiraSchemaPath = "../../../../internal/kiraschema/kiraschema_gen.go"

var initialisms = map[string]string{
	"id": "ID", "json": "JSON", "url": "URL", "uri": "URI", "mcp": "MCP", "sql": "SQL", "api": "API",
	"http": "HTTP", "ip": "IP", "tui": "TUI", "uuid": "UUID", "tls": "TLS", "ssh": "SSH", "html": "HTML",
}

func goName(s string) string {
	var b strings.Builder
	for _, w := range strings.Split(s, "_") {
		if w == "" {
			continue
		}
		if up, ok := initialisms[w]; ok {
			b.WriteString(up)
			continue
		}
		b.WriteString(strings.ToUpper(w[:1]) + w[1:])
	}
	return b.String()
}

type genColumn struct{ Go, SQL string }

type genTable struct {
	Go, SQL string
	Columns []genColumn
}

// migrationOnly tables hold runner state, not app data.
var migrationOnly = map[string]bool{"schema_version": true}

func schemaTables(t *testing.T, db *sql.DB) []genTable {
	t.Helper()
	names, err := db.Query(`SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY name`)
	if err != nil {
		t.Fatal(err)
	}
	var tables []genTable
	for names.Next() {
		var n string
		if err := names.Scan(&n); err != nil {
			t.Fatal(err)
		}
		if !migrationOnly[n] {
			tables = append(tables, genTable{Go: goName(n), SQL: n})
		}
	}
	if err := names.Err(); err != nil {
		t.Fatal(err)
	}
	names.Close()
	for i := range tables {
		cols, err := db.Query(`SELECT name FROM pragma_table_xinfo(?) ORDER BY cid`, tables[i].SQL)
		if err != nil {
			t.Fatal(err)
		}
		for cols.Next() {
			var c string
			if err := cols.Scan(&c); err != nil {
				t.Fatal(err)
			}
			tables[i].Columns = append(tables[i].Columns, genColumn{Go: goName(c), SQL: c})
		}
		if err := cols.Err(); err != nil {
			t.Fatal(err)
		}
		cols.Close()
	}
	return tables
}

var kiraSchemaTmpl = template.Must(template.New("gen").Parse(`// Code generated by TestKiraSchemaGenerated; DO NOT EDIT.

package kiraschema
{{range .}}
// {{.Go}} names table {{.SQL}}.
var {{.Go}} = struct {
	Table string
{{- range .Columns}}
	{{.Go}} string
{{- end}}
}{
	Table: "{{.SQL}}",
{{- range .Columns}}
	{{.Go}}: "{{.SQL}}",
{{- end}}
}
{{end}}`))

func renderKiraSchema(t *testing.T, tables []genTable) []byte {
	t.Helper()
	seen := map[string]string{}
	for _, tb := range tables {
		if prev, dup := seen[tb.Go]; dup {
			t.Fatalf("tables %s and %s share Go name %s", prev, tb.SQL, tb.Go)
		}
		seen[tb.Go] = tb.SQL
		cols := map[string]string{"Table": "(table name)"}
		for _, c := range tb.Columns {
			if prev, dup := cols[c.Go]; dup {
				t.Fatalf("%s: columns %s and %s share Go name %s", tb.SQL, prev, c.SQL, c.Go)
			}
			cols[c.Go] = c.SQL
		}
	}
	var buf bytes.Buffer
	if err := kiraSchemaTmpl.Execute(&buf, tables); err != nil {
		t.Fatal(err)
	}
	out, err := format.Source(buf.Bytes())
	if err != nil {
		t.Fatalf("format generated code: %v\n%s", err, buf.String())
	}
	return out
}

// The generated file is the Go view of the schema: a diff here follows a schema change.
func TestKiraSchemaGenerated(t *testing.T) {
	got := renderKiraSchema(t, schemaTables(t, openFresh(t)))
	if *update {
		if err := os.WriteFile(kiraSchemaPath, got, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(kiraSchemaPath)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Errorf("internal/kiraschema is stale; run go test ./apps/kira-space/internal/storage -run TestKiraSchemaGenerated -update")
	}
}
